#!/usr/bin/env python3
"""
tools/generate_autoconfig.py - Single Source of Truth Generator for Aegis autoconfig.

Generates config/autoconfig/aegis.cfg directly from config/axes/surface/s*.json.
Validates cumulativity (S2 extends S1, S3 extends S2, S4 extends S3) with documented overrides.
Provides a --check flag for CI drift detection.
"""

import argparse
import json
import os
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
SURFACE_DIR = REPO_ROOT / "config" / "axes" / "surface"
TARGET_CFG = REPO_ROOT / "config" / "autoconfig" / "aegis.cfg"

TIERS = ["S1", "S2", "S3", "S4"]


def load_tier_definitions():
    tiers_data = {}
    for tier in TIERS:
        fpath = SURFACE_DIR / f"{tier.lower()}.json"
        if not fpath.is_file():
            sys.exit(f"Missing tier definition: {fpath}")
        with open(fpath, "r", encoding="utf-8") as f:
            tiers_data[tier] = json.load(f)
    return tiers_data


def compute_cumulative_prefs(tiers_data):
    """
    Computes effective preference map per tier and asserts cumulativity.
    Returns: dict of tier -> { pref_name: { "value": val, "locked": bool, "override": bool } }
    """
    effective = {}
    for tier in TIERS:
        data = tiers_data[tier]
        parent = data.get("extends")
        current_prefs = {}
        if parent:
            if parent not in effective:
                sys.exit(f"Tier {tier} extends unknown parent {parent}")
            # Inherit from parent
            for p, meta in effective[parent].items():
                current_prefs[p] = dict(meta)

        # Apply controls from current tier
        for ctrl in data.get("controls", []):
            is_locked = ctrl.get("locked", False)
            is_override = bool(ctrl.get("override_of"))
            for pref_name, pref_val in ctrl.get("set", {}).items():
                current_prefs[pref_name] = {
                    "value": pref_val,
                    "locked": is_locked,
                    "override": is_override,
                    "id": ctrl.get("id")
                }
        effective[tier] = current_prefs

    # Cumulativity assertion
    for i in range(1, len(TIERS)):
        child_tier = TIERS[i]
        parent_tier = TIERS[i - 1]
        parent_prefs = effective[parent_tier]
        child_prefs = effective[child_tier]

        for p, p_meta in parent_prefs.items():
            if p not in child_prefs:
                sys.exit(f"Cumulativity violation: {child_tier} dropped preference '{p}' from {parent_tier}")
            c_meta = child_prefs[p]
            if c_meta["value"] != p_meta["value"] and not c_meta.get("override"):
                sys.exit(
                    f"Cumulativity violation: {child_tier} altered preference '{p}' value ({p_meta['value']} -> {c_meta['value']}) "
                    f"without documented 'override_of' in {child_tier.lower()}.json"
                )

    return effective


def generate_aegis_cfg(effective_prefs):
    """Generates ASCII-only JavaScript for aegis.cfg."""
    lines = [
        "// Aegis Browser - Unified Autoconfig (aegis.cfg)",
        "// AUTO-GENERATED by tools/generate_autoconfig.py. DO NOT EDIT DIRECTLY.",
        "// Single source of truth: config/axes/surface/s*.json",
        "// Tested environment: Firefox ESR 153.5.1esr (64-bit) on Linux x86_64",
        "//",
        "// Security Design:",
        "// 1. General autoconfig sandbox (general.config.sandbox_enabled) is NOT disabled.",
        "// 2. Surface tier is selected exclusively via AEGIS_SURFACE_TIER or profile tier token.",
        "// 3. FAIL-CLOSED: Any unset, unrecognized, or mismatched tier selection automatically",
        "//    locks down to S4 Minimal/Static (JavaScript disabled, JIT off, WASM off, WebGL off).",
        "",
        "// Required comment line for Mozilla autoconfig",
        "",
        "// Universal baseline hardening",
        'lockPref("toolkit.telemetry.enabled", false);',
        'lockPref("toolkit.telemetry.unified", false);',
        'lockPref("datareporting.healthreport.uploadEnabled", false);',
        'lockPref("app.shield.optoutstudies.enabled", false);',
        'lockPref("app.normandy.enabled", false);',
        "",
        "// Detect environment tier",
        'var envTier = "";',
        "try {",
        '  if (typeof getenv === "function") {',
        '    envTier = getenv("AEGIS_SURFACE_TIER");',
        "  }",
        "} catch (e1) {}",
        "",
        "// Detect profile tier from user.js via getPref (native sandbox function)",
        'var profTier = "";',
        "try {",
        '  if (typeof getPref === "function") {',
        '    profTier = getPref("aegis.profile.tier");',
        "  }",
        "} catch (e2) {}",
        "",
        "// Resolve tier with fail-closed validation",
        'var activeTier = "S4"; // Default fail-closed target',
        "var isFailClosed = false;",
        'var failReason = "";',
        "",
        "var candidateTier = envTier || profTier;",
        "",
        "if (!candidateTier) {",
        "  isFailClosed = true;",
        '  failReason = "Unset AEGIS_SURFACE_TIER and no profile tier setting";',
        '} else if (candidateTier !== "S1" && candidateTier !== "S2" && candidateTier !== "S3" && candidateTier !== "S4") {',
        "  isFailClosed = true;",
        '  failReason = "Invalid tier value: " + candidateTier;',
        "} else if (envTier && profTier && envTier !== profTier) {",
        "  isFailClosed = true;",
        '  failReason = "Tier mismatch: env (" + envTier + ") != profile (" + profTier + ")";',
        "} else {",
        "  activeTier = candidateTier;",
        "}",
        "",
        "if (isFailClosed) {",
        '  activeTier = "S4";',
        "  try {",
        '    if (typeof dump === "function") {',
        '      dump("AEGIS_SECURITY_ALERT: " + failReason + " - Failing closed to S4 minimal surface\\n");',
        "    }",
        "  } catch (e3) {}",
        "}",
        "",
        'defaultPref("aegis.surface.active_tier", activeTier);',
        'defaultPref("aegis.surface.fail_closed", isFailClosed);',
        ""
    ]

    for tier in TIERS:
        lines.append(f'if (activeTier === "{tier}") {{')
        lines.append(f"  // Tier {tier}")
        for pref_name, meta in sorted(effective_prefs[tier].items()):
            val = meta["value"]
            if isinstance(val, bool):
                val_str = "true" if val else "false"
            elif isinstance(val, int):
                val_str = str(val)
            else:
                val_str = f'"{val}"'

            fn = "lockPref" if meta["locked"] else "defaultPref"
            lines.append(f'  {fn}("{pref_name}", {val_str});')
        lines.append("} else ")

    # Final else block (fallback to S4 fail-closed)
    lines.append("{")
    lines.append("  // Fallback fail-closed S4")
    for pref_name, meta in sorted(effective_prefs["S4"].items()):
        val = meta["value"]
        val_str = "true" if val is True else ("false" if val is False else (str(val) if isinstance(val, int) else f'"{val}"'))
        lines.append(f'  lockPref("{pref_name}", {val_str});')
    lines.append("}")

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate aegis.cfg from surface JSON specifications")
    parser.add_argument("--check", action="store_true", help="Check for drift between surface JSON and aegis.cfg")
    args = parser.parse_args()

    tiers_data = load_tier_definitions()
    effective_prefs = compute_cumulative_prefs(tiers_data)
    new_cfg = generate_aegis_cfg(effective_prefs)

    # Check ASCII
    try:
        new_cfg.encode("ascii")
    except UnicodeEncodeError as e:
        sys.exit(f"Generated autoconfig contains non-ASCII characters: {e}")

    if args.check:
        if not TARGET_CFG.is_file():
            sys.exit(f"DRIFT: {TARGET_CFG} does not exist. Run without --check to generate.")
        existing = TARGET_CFG.read_text(encoding="ascii")
        if existing != new_cfg:
            sys.exit(f"DRIFT DETECTED: {TARGET_CFG} is out of sync with config/axes/surface/*.json. Re-run tools/generate_autoconfig.py")
        print("OK: config/autoconfig/aegis.cfg is strictly synchronized with config/axes/surface/*.json")
        return

    TARGET_CFG.write_text(new_cfg, encoding="ascii")
    print(f"Generated {TARGET_CFG} successfully from {len(TIERS)} tier definitions.")


if __name__ == "__main__":
    main()
