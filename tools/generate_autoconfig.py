#!/usr/bin/env python3
"""
tools/generate_autoconfig.py - Single Source of Truth Generator for Aegis autoconfig.

Generates config/autoconfig/aegis.cfg directly from:
- config/axes/surface/s*.json (Surface axis)
- config/axes/identity/i*.json (Identity axis)

Validates cumulativity across Surface and Identity axes with documented overrides.
Provides a --check flag for CI drift detection.
"""

import argparse
import json
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
SURFACE_DIR = REPO_ROOT / "config" / "axes" / "surface"
IDENTITY_DIR = REPO_ROOT / "config" / "axes" / "identity"
TARGET_CFG = REPO_ROOT / "config" / "autoconfig" / "aegis.cfg"

SURFACE_TIERS = ["S1", "S2", "S3", "S4"]
IDENTITY_TIERS = ["I1", "I3", "I2", "I4"]


def load_tier_definitions(axis_dir: pathlib.Path = SURFACE_DIR, tiers: list = SURFACE_TIERS) -> dict:
    tiers_data = {}
    for tier in tiers:
        fpath = axis_dir / f"{tier.lower()}.json"
        if not fpath.is_file():
            sys.exit(f"Missing tier definition: {fpath}")
        with open(fpath, "r", encoding="utf-8") as f:
            tiers_data[tier] = json.load(f)
    return tiers_data


def compute_cumulative_prefs(tiers_data: dict, tier_order: list = SURFACE_TIERS, axis_name: str = "Surface") -> dict:
    """
    Computes effective preference map per tier along the cumulative chain and asserts cumulativity.
    Returns: dict of tier -> { pref_name: { "value": val, "locked": bool, "override": bool, "id": str } }
    """
    effective = {}
    for tier in tier_order:
        data = tiers_data[tier]
        parent = data.get("extends")
        current_prefs = {}
        if parent:
            if parent not in effective:
                sys.exit(f"[{axis_name}] Tier {tier} extends unknown parent {parent}")
            # Inherit all controls from parent
            for p, meta in effective[parent].items():
                current_prefs[p] = dict(meta)

        # Apply controls from current tier
        for ctrl in data.get("controls", []):
            is_locked = ctrl.get("locked", False)
            is_override = bool(ctrl.get("override_of"))
            for pref_name, pref_val in ctrl.get("set", {}).items():
                current_prefs[pref_name] = {
                    "value": pref_val,
                    "locked": is_locked,
                    "override": is_override,
                    "id": ctrl.get("id")
                }
        effective[tier] = current_prefs

    # Cumulativity assertion along tier_order
    for idx in range(1, len(tier_order)):
        child_tier = tier_order[idx]
        parent_tier = tier_order[idx - 1]
        parent_prefs = effective[parent_tier]
        child_prefs = effective[child_tier]

        for p, p_meta in parent_prefs.items():
            if p not in child_prefs:
                sys.exit(f"[{axis_name}] Cumulativity violation: {child_tier} dropped preference '{p}' from {parent_tier}")
            c_meta = child_prefs[p]
            if c_meta["value"] != p_meta["value"] and not c_meta.get("override"):
                sys.exit(
                    f"[{axis_name}] Cumulativity violation: {child_tier} altered preference '{p}' value ({p_meta['value']} -> {c_meta['value']}) "
                    f"without documented 'override_of' in {child_tier.lower()}.json"
                )

    return effective


def generate_aegis_cfg(surface_prefs: dict, identity_prefs: dict) -> str:
    """Generates ASCII-only JavaScript for aegis.cfg incorporating Surface and Identity tiers."""
    lines = [
        "// Aegis Browser - Unified Autoconfig (aegis.cfg)",
        "// AUTO-GENERATED by tools/generate_autoconfig.py. DO NOT EDIT DIRECTLY.",
        "// Single sources of truth:",
        "//   - config/axes/surface/s*.json (Surface axis: S1..S4)",
        "//   - config/axes/identity/i*.json (Identity axis: I1..I4)",
        "// Tested environment: Firefox ESR 153.5.1esr (64-bit) on Linux x86_64",
        "//",
        "// Security Design:",
        "// 1. General autoconfig sandbox (general.config.sandbox_enabled) is NOT disabled.",
        "// 2. Surface and Identity tiers are selected via environment variables or profile tokens.",
        "// 3. FAIL-CLOSED: Any unset, unrecognized, or mismatched tier selection automatically",
        "//    locks down to S4 Minimal/Static surface and I4 Minimal-API identity.",
        "",
        "// Required comment line for Mozilla autoconfig",
        "",
        "// ==========================================================================",
        "// Universal Baseline Hardening (Offline-First / Anti-Telemetry)",
        "// ==========================================================================",
        'lockPref("toolkit.telemetry.enabled", false);',
        'lockPref("toolkit.telemetry.unified", false);',
        'lockPref("datareporting.healthreport.uploadEnabled", false);',
        'lockPref("app.shield.optoutstudies.enabled", false);',
        'lockPref("app.normandy.enabled", false);',
        'lockPref("privacy.fingerprintingProtection.remoteOverrides.enabled", false);',
        "",
        "// ==========================================================================",
        "// Surface Tier Resolution & Fail-Closed Logic",
        "// ==========================================================================",
        'var envSurface = "";',
        "try {",
        '  if (typeof getenv === "function") {',
        '    envSurface = getenv("AEGIS_SURFACE_TIER");',
        "  }",
        "} catch (e1) {}",
        "",
        'var profSurface = "";',
        "try {",
        '  if (typeof getPref === "function") {',
        '    profSurface = getPref("aegis.profile.tier");',
        "  }",
        "} catch (e2) {}",
        "",
        'var activeSurface = "S4"; // Default fail-closed target',
        "var isFailClosedSurface = false;",
        'var failReasonSurface = "";',
        "",
        "var candidateSurface = envSurface || profSurface;",
        "",
        "if (!candidateSurface) {",
        "  isFailClosedSurface = true;",
        '  failReasonSurface = "Unset AEGIS_SURFACE_TIER and no profile surface token";',
        '} else if (candidateSurface !== "S1" && candidateSurface !== "S2" && candidateSurface !== "S3" && candidateSurface !== "S4") {',
        "  isFailClosedSurface = true;",
        '  failReasonSurface = "Invalid surface tier value: " + candidateSurface;',
        "} else if (envSurface && profSurface && envSurface !== profSurface) {",
        "  isFailClosedSurface = true;",
        '  failReasonSurface = "Surface tier mismatch: env (" + envSurface + ") != profile (" + profSurface + ")";',
        "} else {",
        "  activeSurface = candidateSurface;",
        "}",
        "",
        "if (isFailClosedSurface) {",
        '  activeSurface = "S4";',
        "  try {",
        '    if (typeof dump === "function") {',
        '      dump("AEGIS_SECURITY_ALERT: " + failReasonSurface + " - Failing closed to S4 minimal surface\\n");',
        "    }",
        "  } catch (e3) {}",
        "}",
        "",
        'defaultPref("aegis.surface.active_tier", activeSurface);',
        'defaultPref("aegis.surface.fail_closed", isFailClosedSurface);',
        "",
        "// ==========================================================================",
        "// Identity Tier Resolution & Fail-Closed Logic",
        "// ==========================================================================",
        'var envIdentity = "";',
        "try {",
        '  if (typeof getenv === "function") {',
        '    envIdentity = getenv("AEGIS_IDENTITY_TIER");',
        "  }",
        "} catch (e4) {}",
        "",
        'var profIdentity = "";',
        "try {",
        '  if (typeof getPref === "function") {',
        '    profIdentity = getPref("aegis.profile.identity_tier");',
        "  }",
        "} catch (e5) {}",
        "",
        'var activeIdentity = "I4"; // Default fail-closed target',
        "var isFailClosedIdentity = false;",
        'var failReasonIdentity = "";',
        "",
        "var candidateIdentity = envIdentity || profIdentity;",
        "",
        "if (!candidateIdentity) {",
        "  // No identity tier supplied by launcher or profile token: fail closed.",
        "  // Auto-resolution from surface tier is prohibited: it can yield I3/I4 on a Tor",
        "  // surface tier, violating R2 (Tor mode strictly locks Identity to I2).",
        "  // The launcher MUST always supply AEGIS_IDENTITY_TIER from the preset table.",
        "  isFailClosedIdentity = true;",
        '  failReasonIdentity = "Unset AEGIS_IDENTITY_TIER and no profile identity token: launcher must supply tier from preset table";',
        '} else if (candidateIdentity !== "I1" && candidateIdentity !== "I2" && candidateIdentity !== "I3" && candidateIdentity !== "I4") {',
        "  isFailClosedIdentity = true;",
        '  failReasonIdentity = "Invalid identity tier value: " + candidateIdentity;',
        "} else if (envIdentity && profIdentity && envIdentity !== profIdentity) {",
        "  isFailClosedIdentity = true;",
        '  failReasonIdentity = "Identity tier mismatch: env (" + envIdentity + ") != profile (" + profIdentity + ")";',
        "} else {",
        "  activeIdentity = candidateIdentity;",
        "}",
        "",
        "if (isFailClosedIdentity) {",
        '  activeIdentity = "I4";',
        "  try {",
        '    if (typeof dump === "function") {',
        '      dump("AEGIS_SECURITY_ALERT: " + failReasonIdentity + " - Failing closed to I4 minimal identity\\n");',
        "    }",
        "  } catch (e6) {}",
        "}",
        "",
        'defaultPref("aegis.identity.active_tier", activeIdentity);',
        'defaultPref("aegis.identity.fail_closed", isFailClosedIdentity);',
        "",
        "// ==========================================================================",
        "// Surface Tier Enforcement",
        "// =========================================================================="
    ]

    for tier in SURFACE_TIERS:
        lines.append(f'if (activeSurface === "{tier}") {{')
        lines.append(f"  // Surface Tier {tier}")
        for pref_name, meta in sorted(surface_prefs[tier].items()):
            val = meta["value"]
            val_str = "true" if val is True else ("false" if val is False else (str(val) if isinstance(val, int) else f'"{val}"'))
            fn = "lockPref" if meta["locked"] else "defaultPref"
            lines.append(f'  {fn}("{pref_name}", {val_str});')
        lines.append("} else ")

    # Fallback fail-closed S4
    lines.append("{")
    lines.append("  // Fallback fail-closed S4")
    for pref_name, meta in sorted(surface_prefs["S4"].items()):
        val = meta["value"]
        val_str = "true" if val is True else ("false" if val is False else (str(val) if isinstance(val, int) else f'"{val}"'))
        lines.append(f'  lockPref("{pref_name}", {val_str});')
    lines.append("}")
    lines.append("")

    lines.append("// ==========================================================================")
    lines.append("// Identity Tier Enforcement")
    lines.append("// ==========================================================================")

    for tier in ["I1", "I3", "I2", "I4"]:
        lines.append(f'if (activeIdentity === "{tier}") {{')
        lines.append(f"  // Identity Level {tier}")
        for pref_name, meta in sorted(identity_prefs[tier].items()):
            val = meta["value"]
            val_str = "true" if val is True else ("false" if val is False else (str(val) if isinstance(val, int) else f'"{val}"'))
            fn = "lockPref" if meta["locked"] else "defaultPref"
            lines.append(f'  {fn}("{pref_name}", {val_str});')
        lines.append("} else ")

    # Fallback fail-closed I4
    lines.append("{")
    lines.append("  // Fallback fail-closed I4")
    for pref_name, meta in sorted(identity_prefs["I4"].items()):
        val = meta["value"]
        val_str = "true" if val is True else ("false" if val is False else (str(val) if isinstance(val, int) else f'"{val}"'))
        lines.append(f'  lockPref("{pref_name}", {val_str});')
    lines.append("}")

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate aegis.cfg from Surface and Identity specifications")
    parser.add_argument("--check", action="store_true", help="Check for drift between axis JSON files and aegis.cfg")
    args = parser.parse_args()

    surface_data = load_tier_definitions(SURFACE_DIR, SURFACE_TIERS)
    identity_data = load_tier_definitions(IDENTITY_DIR, IDENTITY_TIERS)

    surface_effective = compute_cumulative_prefs(surface_data, SURFACE_TIERS, "Surface")
    identity_effective = compute_cumulative_prefs(identity_data, IDENTITY_TIERS, "Identity")

    new_cfg = generate_aegis_cfg(surface_effective, identity_effective)

    # Check ASCII
    try:
        new_cfg.encode("ascii")
    except UnicodeEncodeError as e:
        sys.exit(f"Generated autoconfig contains non-ASCII characters: {e}")

    if args.check:
        if not TARGET_CFG.is_file():
            sys.exit(f"DRIFT: {TARGET_CFG} does not exist. Run without --check to generate.")
        existing = TARGET_CFG.read_text(encoding="ascii")
        if existing != new_cfg:
            sys.exit(f"DRIFT DETECTED: {TARGET_CFG} is out of sync with config/axes/ (surface or identity). Re-run tools/generate_autoconfig.py")
        print("OK: config/autoconfig/aegis.cfg is strictly synchronized with config/axes/surface/*.json and identity/*.json")
        return

    TARGET_CFG.write_text(new_cfg, encoding="ascii")
    print(f"Generated {TARGET_CFG} successfully from {len(SURFACE_TIERS)} surface and {len(IDENTITY_TIERS)} identity definitions.")


if __name__ == "__main__":
    main()
